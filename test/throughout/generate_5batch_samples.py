def write_workbook(samples: list[Sample]) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    ws = wb.active
    ws.title = "samples"
    ws.append(["messages", "correct_label", "batch"])
    for s in samples:
        ws.append([
            json.dumps(s.messages, ensure_ascii=False),
            label(s.correct_label),
            s.batch,
        ])
    ws.column_dimensions["A"].width = 90
    ws.column_dimensions["B"].width = 35
    ws.column_dimensions["C"].width = 12
    wb.save(OUT_FILE)


if __name__ == "__main__":
    samples = build_samples()
    write_workbook(samples)
    print(f"Wrote {len(samples)} samples to {OUT_FILE}")
