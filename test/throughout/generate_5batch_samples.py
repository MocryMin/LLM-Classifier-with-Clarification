def batch2_risk() -> list[Sample]:
    samples = [
        Sample([u("我要转人工客服，不涉及具体业务，就是想让人工帮我看一下。")], {"risk_level": "high"}, "2.1"),
        Sample([u("你们这个客服太让人生气了，我现在很火大！")], {"risk_level": "high"}, "2.1"),
        Sample([u("我今天心情有点低落，想随便了解一下你们客服能提供哪些帮助。")], {"risk_level": "low"}, "2.1"),
        Sample([u("你觉得今天中午吃面还是吃米饭比较好？")], {"risk_level": "low"}, "2.1"),
    ]
    samples.extend(Sample([u(text)], {"risk_level": risk}, "2.2") for _scene, risk, text in RISK_SCENE_CASES)
    assert len(samples) == 36
    return samples


